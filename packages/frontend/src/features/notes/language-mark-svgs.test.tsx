import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { CODE_LANGUAGE_MARKS } from "#/lib/code-language-marks.ts";
import { CODE_LANGUAGES } from "./code-languages";

const FILE = join(__dirname, "../../lib/code-language-marks.ts");

/// Each language's mark as the phone draws it: the desktop's own SVG, written out, with the
/// colour of a Tabler mark (SQL, Assembly) put in place of `currentColor`.
function marks() {
  return CODE_LANGUAGES.map((lang) => {
    const html = renderToStaticMarkup(<lang.icon />);
    const color = /color:\s*(#[0-9A-Fa-f]{6})/.exec(html)?.[1];
    const svg = (color ? html.replaceAll("currentColor", color) : html)
      .replace(/ style="[^"]*"/g, "")
      .replace(/ class="[^"]*"/g, "")
      .replace(/ aria-hidden="true"/g, "");
    return { value: lang.value, label: lang.label, svg };
  });
}

function source(): string {
  const entries = marks().map((mark) => `  ${JSON.stringify(mark)},`);
  return `// Generated by \`features/notes/language-mark-svgs.test.tsx\` from \`CODE_LANGUAGES\`
// (NOOKLY_UPDATE_MARKS=1 bunx vitest run language-mark-svgs). Do not edit by hand.

/// Every language the code block picker offers, with its coloured mark as SVG text, for
/// the phone, which cannot draw the desktop's components.
export const CODE_LANGUAGE_MARKS: { value: string; label: string; svg: string }[] = [
${entries.join("\n")}
];
`;
}

describe("the phone's language marks", () => {
  it("are the desktop's, written out", () => {
    // Rewritten, then run through the formatter (`bun run format`).
    if (process.env.NOOKLY_UPDATE_MARKS) writeFileSync(FILE, source());
    expect(CODE_LANGUAGE_MARKS).toEqual(marks());
  });
});
