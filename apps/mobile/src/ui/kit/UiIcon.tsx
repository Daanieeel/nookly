/// An interface icon: its SF Symbol on iOS, the Tabler icon elsewhere or when it has no
/// symbol. A drop-in for `<IconX size color />`.
export function UiIcon({
  icon,
  size = 17,
  color = "#8e8e93",
  weight = "regular",
}: {
  icon: FallbackIcon;
  size?: number;
  color?: string;
  weight?: SymbolViewProps["weight"];
}) {
  const Fallback = icon;
  const name = INTERFACE_SYMBOLS.get(icon);
  if (!name) return <Fallback size={size} color={color} />;
  return (
    <Glyph name={name} fallback={icon} size={size} color={color} hex={color} weight={weight} />
  );
}
